/**
 * subpath-shims.mjs — keeps the public deep-import surface flat while the source
 * tree is organised by category.
 *
 * Source lives at   src/components/<category>/<slug>.tsx
 * Consumers import  @qeetrix/ui/components/<slug>        (canonical, unchanged)
 *                   @qeetrix/ui/components/ui/<slug>     (legacy, pre-1.0)
 *                   @qeetrix/ui/components/<category>    (group import)
 *
 * After tsc emits dist/components/<category>/<slug>.js, this writes the thin
 * re-export files those specifiers resolve to. Moving a component between
 * categories therefore never breaks a consumer — only the shim target changes.
 *
 * Runs as part of `bun run build`, after tsc + tsc-alias.
 */
import { existsSync, mkdirSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "../..");
const DIST_COMPONENTS = join(ROOT, "dist/components");
const DIST_PROVIDERS = join(ROOT, "dist/providers");

if (!existsSync(DIST_COMPONENTS)) {
  console.error("✗ dist/components is missing — run tsc before subpath-shims.");
  process.exit(1);
}

const banner = (target) =>
  `// GENERATED by scripts/build/subpath-shims.mjs — re-export of ${target}.\n`;

let files = 0;
const write = (path, target, kind) => {
  mkdirSync(dirname(path), { recursive: true });
  const from = kind === "types" ? target.replace(/\.js$/, ".js") : target;
  writeFileSync(path, `${banner(target)}export * from "${from}";\n`);
  files += 1;
};

const categories = readdirSync(DIST_COMPONENTS, { withFileTypes: true })
  .filter((e) => e.isDirectory() && e.name !== "ui")
  .map((e) => e.name);

for (const category of categories) {
  const dir = join(DIST_COMPONENTS, category);
  const slugs = readdirSync(dir)
    .filter((f) => f.endsWith(".js") && f !== "index.js")
    .map((f) => f.replace(/\.js$/, ""));

  for (const slug of slugs) {
    // @qeetrix/ui/components/<slug>
    write(join(DIST_COMPONENTS, `${slug}.js`), `./${category}/${slug}.js`, "js");
    write(join(DIST_COMPONENTS, `${slug}.d.ts`), `./${category}/${slug}.js`, "types");
    // @qeetrix/ui/components/ui/<slug> — legacy path kept alive for pre-1.0 consumers.
    write(join(DIST_COMPONENTS, "ui", `${slug}.js`), `../${category}/${slug}.js`, "js");
    write(join(DIST_COMPONENTS, "ui", `${slug}.d.ts`), `../${category}/${slug}.js`, "types");
  }

  // @qeetrix/ui/components/<category> — group import, resolved by the same wildcard.
  if (existsSync(join(dir, "index.js"))) {
    write(join(DIST_COMPONENTS, `${category}.js`), `./${category}/index.js`, "js");
    write(join(DIST_COMPONENTS, `${category}.d.ts`), `./${category}/index.js`, "types");
  }
}

// Providers moved to src/providers/, but @qeetrix/ui/components/<name>-provider
// is part of the published surface — keep it resolvable.
if (existsSync(DIST_PROVIDERS)) {
  for (const file of readdirSync(DIST_PROVIDERS)) {
    if (!file.endsWith(".js") || file === "index.js") continue;
    const slug = file.replace(/\.js$/, "");
    write(join(DIST_COMPONENTS, `${slug}.js`), `../providers/${slug}.js`, "js");
    write(join(DIST_COMPONENTS, `${slug}.d.ts`), `../providers/${slug}.js`, "types");
  }
}

console.log(
  `✔ subpath shims: ${files} files (flat, legacy ui/, category group imports, providers)`,
);
